import { execFileSync, spawn } from "node:child_process";
import { build, context, type BuildContext, type BuildOptions } from "esbuild";
import {
  copyFileSync,
  mkdirSync,
  readFileSync,
  renameSync,
  rmSync,
  statSync,
  watchFile,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const command: string | undefined = process.argv[2];
const devTargetArg: string | undefined = process.argv[3];
const devTarget: "chrome" | "firefox" =
  devTargetArg === "firefox" ? "firefox" : "chrome";
if (
  (command !== "chrome" &&
    command !== "firefox" &&
    command !== "dist" &&
    command !== "dev") ||
  (command === "dev" &&
    devTargetArg !== undefined &&
    devTargetArg !== "chrome" &&
    devTargetArg !== "firefox")
) {
  console.error(
    "Usage: node build.ts <chrome|firefox|dist|dev [chrome|firefox]>",
  );
  process.exit(1);
}

const root = join(dirname(fileURLToPath(import.meta.url)));
const buildBanner =
  "// Generated by build.ts — do not edit. Rebuild with: node build.ts <chrome|firefox>\n";

// Runtime files staged for the release artifacts (zips, xpi, crx).
const distFiles = [
  "background.js",
  "LICENSE",
  "content/bundle.js",
  "content/content.css",
  "options/options.html",
  "options/options.bundle.js",
  "options/options.css",
  "popup/popup.html",
  "popup/popup.css",
  "popup/popup.bundle.js",
  "icons/icon-16.png",
  "icons/icon-32.png",
  "icons/icon-48.png",
  "icons/icon-128.png",
];

// The docs/ demo site stays out of the packaged artifacts (CI relied on a
// source-text grep for this before the check moved here; now every build
// invocation enforces it for real).
if (distFiles.some((file) => /(^|[/\\])(docs|demo)([/\\]|$)/i.test(file))) {
  throw new Error("docs/ must not be packaged");
}

// One entry per bundle; [dir, entry, outfile]. The content entry name is kept
// as "content.js" so esbuild resolves it to content/content.ts.
const entries: Array<[string, string, string]> = [
  ["content", "content.js", "bundle.js"],
  ["options", "options.js", "options.bundle.js"],
  ["popup", "popup.js", "popup.bundle.js"],
  ["background", "main.ts", "background.js"],
];

// Dev watches hold the esbuild daemons; esbuild tears down a watch when its
// context object becomes garbage, so keep every context alive for the whole
// dev-mode process lifetime (see watchOne).
const devContexts: BuildContext[] = [];

if (command === "dev") {
  await dev(devTarget);
} else if (command === "dist") {
  for (const [dir, entry, outfile] of entries) {
    await buildOne(dir, entry, outfile, buildBanner);
  }
  console.log("Wrote content/bundle.js");
  console.log("Wrote options/options.bundle.js");
  console.log("Wrote popup/popup.bundle.js");
  console.log("Wrote background.js");

  buildDist("chrome");
  buildDist("firefox");
} else {
  for (const [dir, entry, outfile] of entries) {
    await buildOne(dir, entry, outfile, buildBanner);
  }
  console.log("Wrote content/bundle.js");
  console.log("Wrote options/options.bundle.js");
  console.log("Wrote popup/popup.bundle.js");
  console.log("Wrote background.js");

  writeManifest(command);
  console.log(
    `Load this folder in ${command === "chrome" ? "Chrome" : "Firefox"}.`,
  );
}

// Only the fields build.ts reads or mutates are declared; the rest of the
// manifest shape stays governed by manifest.base.json (the committed source
// of truth).
type Manifest = {
  version: string;
  background: { service_worker?: string; scripts?: string[] };
  browser_specific_settings?: Record<string, unknown>;
  permissions: string[];
  [key: string]: unknown;
};

function manifestFor(target: "chrome" | "firefox"): Manifest {
  const manifest = JSON.parse(
    readFileSync(join(root, "manifest.base.json"), "utf8"),
  ) as Manifest;
  if (target === "chrome") {
    manifest.background = { service_worker: "background.js" };
    delete manifest.browser_specific_settings;
    // Tab grouping is Chrome-only; Firefox builds omit it and the tab
    // manager falls back with an honest toast.
    if (!manifest.permissions.includes("tabGroups")) {
      manifest.permissions.push("tabGroups");
    }
  } else {
    manifest.background = { scripts: ["background.js"] };
    manifest.permissions.push("clipboardWrite");
  }
  return manifest;
}

function writeManifest(target: "chrome" | "firefox"): void {
  writeFileSync(
    join(root, "manifest.json"),
    JSON.stringify(manifestFor(target), null, 2) + "\n",
  );
  console.log(`Wrote manifest.json (${target})`);
}

function buildDist(target: "chrome" | "firefox"): void {
  const manifest = manifestFor(target);
  const stage = join(root, "dist", `jari-${target}`);
  rmSync(stage, { recursive: true, force: true });
  for (const file of distFiles) {
    mkdirSync(join(stage, dirname(file)), { recursive: true });
    copyFileSync(join(root, file), join(stage, file));
  }
  writeFileSync(
    join(stage, "manifest.json"),
    JSON.stringify(manifest, null, 2) + "\n",
  );
  if (target === "firefox") {
    buildFirefoxXpi(stage, manifest.version);
  } else {
    buildChromeZip(stage, manifest.version);
    packChromeCrx(stage, manifest.version);
  }
}

function crxKeyPem(): string | null {
  const raw = String(process.env.CRX_PRIVATE_KEY || "");
  if (!raw.trim()) return null;
  const decoded = Buffer.from(raw.replace(/\s+/g, ""), "base64").toString(
    "utf8",
  );
  if (decoded.includes("PRIVATE KEY")) return decoded;
  if (raw.includes("PRIVATE KEY")) return raw;
  throw new Error(
    "CRX_PRIVATE_KEY must be the base64 output of `base64 -w0 key.pem` (or the .pem text itself)",
  );
}

function runNodeBin(bin: string, args: string[]): void {
  execFileSync(process.execPath, [bin, ...args], { stdio: "inherit" });
}

function buildFirefoxXpi(stage: string, version: string): void {
  const webExt = join(root, "node_modules", "web-ext", "bin", "web-ext.js");
  runNodeBin(webExt, ["lint", "--source-dir", stage]);
  const zip = join(root, "dist", `jari-${version}.zip`);
  rmSync(zip, { force: true });
  runNodeBin(webExt, [
    "build",
    "--source-dir",
    stage,
    "--artifacts-dir",
    join(root, "dist"),
    "--overwrite-dest",
  ]);
  const xpi = join(root, "dist", `jari-firefox-${version}-unsigned.xpi`);
  rmSync(xpi, { force: true });
  renameSync(zip, xpi);
  console.log(`Wrote ${xpi}`);
}

function buildChromeZip(stage: string, version: string): void {
  const zip = join(root, "dist", `jari-chrome-${version}.zip`);
  rmSync(zip, { force: true });
  execFileSync("zip", ["-qr", zip, "."], { cwd: stage });
  console.log(`Wrote ${zip}`);
}

function packChromeCrx(stage: string, version: string): void {
  const pem = crxKeyPem();
  if (!pem) {
    console.log("Skipping CRX pack (CRX_PRIVATE_KEY not set)");
    return;
  }
  const keyFile = join(tmpdir(), `jari-crx-key-${process.pid}.pem`);
  writeFileSync(keyFile, pem, { mode: 0o600 });
  try {
    const crx = join(root, "dist", `jari-chrome-${version}.crx`);
    rmSync(crx, { force: true });
    runNodeBin(join(root, "node_modules", "crx3", "bin", "crx3.js"), [
      stage,
      "-o",
      crx,
      "-p",
      keyFile,
    ]);
  } finally {
    rmSync(keyFile, { force: true });
  }
}

async function buildOne(
  dir: string,
  entry: string,
  outfile: string,
  banner: string,
): Promise<void> {
  const outPath = join(root, dir === "background" ? "." : dir, outfile);
  await build(bundleOptions(dir, entry, outPath, banner));

  const firstLine = readFileSync(outPath, "utf8").split("\n", 1)[0];
  if (firstLine !== buildBanner.trim()) {
    throw new Error(`Banner missing from ${outPath}`);
  }
}

function bundleOptions(
  dir: string,
  entry: string,
  outPath: string,
  banner: string,
): BuildOptions {
  return {
    entryPoints: [join(root, dir, entry)],
    bundle: true,
    format: "iife",
    outfile: outPath,
    banner: { js: banner },
    logLevel: "warning",
    minify: true,
  };
}

// Dev watch mode: `npm run dev:chrome|:firefox`. Same options as release
// builds but unminified for readable output, plus sourcemaps (release
// output stays map-free and byte-stable), rebuilt on every source edit.
// manifest.base.json is not an esbuild input,
// so the contexts never see edits to it — poll-stat it and regenerate the
// manifest when it changes. The firefox flavor additionally launches
// `web-ext run` so the extension auto-reloads in Firefox on every rebuild.
async function dev(devTarget: "chrome" | "firefox"): Promise<void> {
  for (const [dir, entry, outfile] of entries) {
    devContexts.push(await watchOne(dir, entry, outfile, buildBanner));
  }
  writeManifest(devTarget);

  const baseManifest = join(root, "manifest.base.json");
  let mtimeMs = statSync(baseManifest).mtimeMs;
  watchFile(baseManifest, { interval: 500 }, (now) => {
    if (now.mtimeMs === mtimeMs) return;
    mtimeMs = now.mtimeMs;
    writeManifest(devTarget);
  });

  if (devTarget === "firefox") {
    launchWebExtRun();
  } else {
    console.log("Load this folder in Chrome. Watching for changes…");
  }
  await new Promise(() => {});
}

// Firefox flavor of dev watch: run the repo root under `web-ext run` so
// the extension installs into a throwaway profile and reloads on every
// esbuild rebuild. Heavy local-only trees stay out of the packaged reload
// via --ignore-files/--watch-ignored. A web-ext failure (no Firefox,
// no display) only costs auto-reload — the esbuild watch keeps running.
function launchWebExtRun(): void {
  const webExt = join(root, "node_modules", "web-ext", "bin", "web-ext.js");
  const child = spawn(
    process.execPath,
    [
      webExt,
      "run",
      "--source-dir",
      root,
      "--artifacts-dir",
      join(tmpdir(), "jari-web-ext-run"),
      "--ignore-files",
      "node_modules",
      "dist",
      ".git",
      "web-ext-artifacts",
      "--watch-ignored",
      "node_modules/**",
      "dist/**",
      ".git/**",
      "--no-config-discovery",
    ],
    { stdio: "inherit" },
  );
  child.on("error", (err) => {
    console.error(
      `web-ext run failed to start (${err.message}); watching without auto-reload.`,
    );
  });
  child.on("exit", (code) => {
    console.log(
      `web-ext run exited (${code}); esbuild watch is still running.`,
    );
  });
}

async function watchOne(
  dir: string,
  entry: string,
  outfile: string,
  banner: string,
): Promise<BuildContext> {
  const outPath = join(root, dir === "background" ? "." : dir, outfile);
  const ctx = await context({
    ...bundleOptions(dir, entry, outPath, banner),
    sourcemap: true,
    minify: false,
  });
  await ctx.watch();
  console.log(`Watching ${outPath}`);
  return ctx;
}
