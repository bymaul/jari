// Concatenates the content scripts into content/bundle.js and generates
// manifest.json for the target browser.
// Usage: node build.js <chrome|firefox>
const fs = require("fs");
const path = require("path");

const target = process.argv[2];
if (target !== "chrome" && target !== "firefox") {
  console.error("Usage: node build.js <chrome|firefox>");
  process.exit(1);
}

// The content scripts, in dependency order: keymap first (defaults + shared
// helpers), then the store and UI primitives, then each feature, and the
// entry point last. The manifests and the options page load this single
// bundle, so this list is the source of truth.
const CONTENT_SCRIPTS = [
  "keymap.js",
  "settings.js",
  "ui.js",
  "commands.js",
  "scroll.js",
  "hints.js",
  "prompt.js",
  "help.js",
  "content.js",
];

const contentDir = path.join(__dirname, "content");
const bundlePath = path.join(contentDir, "bundle.js");
const banner = `// Generated by build.js — do not edit. Rebuild with: node build.js <chrome|firefox>\n`;
const bundle = CONTENT_SCRIPTS.map((file) => {
  const source = fs.readFileSync(path.join(contentDir, file), "utf8");
  return `// ---- ${file} ----\n${source}`;
}).join("\n");
fs.writeFileSync(bundlePath, banner + bundle);

const src = path.join(__dirname, `manifest.${target}.json`);
const dest = path.join(__dirname, "manifest.json");

if (!fs.existsSync(src)) {
  console.error(`Missing source manifest: ${src}`);
  process.exit(1);
}

fs.copyFileSync(src, dest);
console.log(`Wrote content/bundle.js (${CONTENT_SCRIPTS.length} scripts)`);
console.log(`Wrote manifest.json from manifest.${target}.json`);
console.log(`Load this folder in ${target === "chrome" ? "Chrome" : "Firefox"}.`);
