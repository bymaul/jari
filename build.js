// Bundles the content scripts, the options page and the background service
// worker into classic IIFE bundles (content scripts cannot use ES imports at
// runtime, and the background manifest entry must stay a single classic
// file) and generates manifest.json for the target browser.
// Usage: node build.js <chrome|firefox>
import { build } from "esbuild";
import { copyFileSync, existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const target = process.argv[2];
if (target !== "chrome" && target !== "firefox") {
  console.error("Usage: node build.js <chrome|firefox>");
  process.exit(1);
}

const root = join(dirname(fileURLToPath(import.meta.url)));
const rebuildHint =
  "// Generated by build.js — do not edit. Rebuild with: node build.js <chrome|firefox>\n";

// content/bundle.js is the content-script entry: it imports the feature
// modules, so esbuild resolves the dependency graph instead of the previous
// hardcoded concatenation order.
// options/options.bundle.js is the options-page script. It imports the same
// modules for its own UI (settings, commands, keymap helpers); the page also
// loads content/bundle.js so Jari's content features work on it.
// background.js is the service worker: main.js wires the runtime listener and
// imports the handlers, which in turn import the shared constants module.
await buildOne("content", "content.js", "bundle.js", rebuildHint);
await buildOne(
  "options",
  "options.js",
  "options.bundle.js",
  "// Generated by build.js — do not edit.\n",
);
await buildOne("background", "main.js", "background.js", rebuildHint);

const src = join(root, `manifest.${target}.json`);
const dest = join(root, "manifest.json");
if (!existsSync(src)) {
  console.error(`Missing source manifest: ${src}`);
  process.exit(1);
}
copyFileSync(src, dest);

console.log("Wrote content/bundle.js");
console.log("Wrote options/options.bundle.js");
console.log("Wrote background.js");
console.log(`Wrote manifest.json from manifest.${target}.json`);
console.log(
  `Load this folder in ${target === "chrome" ? "Chrome" : "Firefox"}.`,
);

// Bundle an entry point into a classic IIFE under the source directory.
async function buildOne(dir, entry, outfile, banner) {
  const outPath = join(root, dir === "background" ? "." : dir, outfile);
  await build({
    entryPoints: [join(root, dir, entry)],
    bundle: true,
    format: "iife",
    outfile: outPath,
    banner: { js: banner },
    logLevel: "warning",
  });
  // The banner is the first line of the bundle; without a `//` prefix the
  // file would start with bare text and fail to parse as a classic script.
  const firstLine = readFileSync(outPath, "utf8").split("\n", 1)[0];
  if (!firstLine.startsWith("//")) {
    throw new Error(`Banner missing from ${outPath}`);
  }
}
